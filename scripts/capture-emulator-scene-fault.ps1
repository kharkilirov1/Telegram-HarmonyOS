#requires -Version 7.0
# Read-only guest diagnostics. JSONL on stdout; no profile/reset/install/security changes.
param(
  [string]$HdcPath = 'C:/Program Files/Huawei/DevEco Studio/sdk/default/openharmony/toolchains/hdc.exe',
  [string]$Target = '127.0.0.1:10023',
  [ValidateRange(10, 900)][int]$DurationSeconds = 420,
  [string]$KernelLog = '',
  [datetime]$BootStartedAt = [datetime]::MinValue,
  [string]$RecoveryFaultFile = '',
  [string]$RecoveryFaultDestination = '',
  [string]$LoaderArtifactDirectory = '',
  [switch]$ProbeOnly
)
$ErrorActionPreference = 'Stop'
if ($Target -notmatch '^127\.0\.0\.1:(1[0-6][0-9]{3})$') { throw 'Use an explicit local emulator port' }
if (-not (Test-Path -LiteralPath $HdcPath -PathType Leaf)) { throw 'HDC client is missing' }

function Invoke-Client {
  param([string[]]$ClientArguments, [int]$TimeoutMs = 5000, [int]$Limit = 18000)
  $info = [Diagnostics.ProcessStartInfo]::new()
  $info.FileName = $HdcPath
  $info.UseShellExecute = $false
  $info.CreateNoWindow = $true
  $info.RedirectStandardOutput = $true
  $info.RedirectStandardError = $true
  foreach ($argument in $ClientArguments) { $info.ArgumentList.Add($argument) }
  $process = [Diagnostics.Process]::new()
  $process.StartInfo = $info
  try {
    if (-not $process.Start()) { throw 'Could not start diagnostic client' }
    $stdout = $process.StandardOutput.ReadToEndAsync()
    $stderr = $process.StandardError.ReadToEndAsync()
    $ended = $process.WaitForExit($TimeoutMs)
    if (-not $ended) {
      # Only this owned, bounded client is stopped, never the shared HDC server.
      $process.Kill()
      $null = $process.WaitForExit(2000)
    }
    $out = if ($stdout.IsCompleted) { $stdout.Result } else { '[stdout incomplete]' }
    $err = if ($stderr.IsCompleted) { $stderr.Result } else { '[stderr incomplete]' }
    [pscustomobject]@{
      exit = if ($ended) { $process.ExitCode } else { $null }
      timeout = -not $ended
      stdout = $out.Substring(0, [Math]::Min($Limit, $out.Length))
      stderr = $err.Substring(0, [Math]::Min(2000, $err.Length))
      truncated = $out.Length -gt $Limit
    }
  } finally { $process.Dispose() }
}
function Emit {
  param([string]$Kind, [object]$Data)
  [pscustomobject]@{time = (Get-Date).ToString('o'); kind = $Kind; data = $Data} |
    ConvertTo-Json -Depth 6 -Compress
}
function Find-FreshKernelPanic {
  param([string[]]$Lines, [datetime]$NotBefore)
  foreach ($line in $Lines) {
    if ($line -notmatch '^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3} .*Kernel panic - not syncing') { continue }
    $timestamp = [datetime]::MinValue
    if ([datetime]::TryParseExact($line.Substring(0, 23), 'yyyy-MM-dd HH:mm:ss.fff',
      [Globalization.CultureInfo]::InvariantCulture, [Globalization.DateTimeStyles]::None,
      [ref]$timestamp) -and $timestamp -ge $NotBefore) { $line }
  }
}
function Test-GuestReady {
  param([object]$Result)
  return -not $Result.timeout -and $Result.exit -eq 0 -and
    $Result.stdout -cmatch '(?m)^WAVE10_READY\r?$'
}
function Test-FaultCapture {
  param([object]$Result)
  # HDC can return exit 0 with a disconnected-device error on stdout.
  return -not $Result.timeout -and $Result.exit -eq 0 -and
    $Result.stdout.StartsWith('Generated by HiviewDFX@OpenHarmony')
}
function Find-SceneProcessIds {
  param([string]$ProcessText, [string]$ErrorText)
  $ids = [Collections.Generic.HashSet[int]]::new()
  foreach ($match in [regex]::Matches($ProcessText, '(?m)^\S+\s+(\d+)\s+\d+[^\r\n]*\s+(?:com\.)?ohos\.sceneboard\r?$')) {
    $value = 0
    if ([int]::TryParse($match.Groups[1].Value, [ref]$value) -and $value -gt 0) { $null = $ids.Add($value) }
  }
  foreach ($match in [regex]::Matches($ErrorText, 'key:(\d+)_\d+_com\.ohos\.sceneboard')) {
    $value = 0
    if ([int]::TryParse($match.Groups[1].Value, [ref]$value) -and $value -gt 0) { $null = $ids.Add($value) }
  }
  foreach ($value in $ids) { $value }
}
if ($ProbeOnly) {
  Emit 'clientProbe' (Invoke-Client -ClientArguments @('-v'))
  exit
}
$deadline = (Get-Date).AddSeconds($DurationSeconds)
$started = if ($BootStartedAt -eq [datetime]::MinValue) { Get-Date } else { $BootStartedAt }
$seen = [Collections.Generic.Dictionary[string, string]]::new()
$ready = $false
$recovered = $false
$loaderCollected = $false
$pidLogs = [Collections.Generic.Dictionary[int, string]]::new()
$lastConnect = [datetime]::MinValue
Emit 'monitorStart' @{target=$Target; durationSeconds=$DurationSeconds}
while ((Get-Date) -lt $deadline) {
  if ($KernelLog.Length -gt 0 -and (Test-Path -LiteralPath $KernelLog)) {
    $kernel = Get-Item -LiteralPath $KernelLog
    if ($kernel.LastWriteTime -gt $started) {
      # Emulator may append/reopen an old log. Fresh mtime alone is not a new panic.
      $panic = @(Find-FreshKernelPanic -Lines (Get-Content -LiteralPath $KernelLog -Tail 150) -NotBefore $started)
      if ($panic.Count -gt 0) { Emit 'kernelPanic' $panic; break }
    }
  }
  if (-not $ready -and ((Get-Date) - $lastConnect).TotalSeconds -ge 12) {
    Emit 'connect' (Invoke-Client -ClientArguments @('tconn', $Target) -TimeoutMs 3500)
    $lastConnect = Get-Date
  }
  $probe = Invoke-Client -ClientArguments @('-t', $Target, 'shell',
    'echo WAVE10_READY; date; ps -ef | grep -i -E "scene|render_service|appspawn"') -TimeoutMs 3500
  if (-not (Test-GuestReady $probe)) {
    if ($ready) { Emit 'shellLost' $probe }
    $ready = $false
    Start-Sleep -Seconds 3
    continue
  }
  if (-not $ready) {
    Emit 'shellReady' $probe
    if (-not $loaderCollected -and $LoaderArtifactDirectory.Length -gt 0) {
      foreach ($remote in @('/system/lib/ld-musl-x86_64.so.1', '/system/lib64/platformsdk/libace_napi.z.so')) {
        $destination = [IO.Path]::GetFullPath((Join-Path $LoaderArtifactDirectory (Split-Path $remote -Leaf)))
        Emit 'loaderArtifact' @{remote=$remote; result=(Invoke-Client -ClientArguments @('-t', $Target,
          'file', 'recv', $remote, $destination) -TimeoutMs 15000)}
      }
      $loaderCollected = $true
    }
    if (-not $recovered -and $RecoveryFaultFile -match '^[A-Za-z0-9._-]+$' -and $RecoveryFaultDestination.Length -gt 0) {
      $recovery = Invoke-Client -ClientArguments @('-t', $Target, 'file', 'recv',
        "/data/log/faultlog/faultlogger/$RecoveryFaultFile",
        [IO.Path]::GetFullPath($RecoveryFaultDestination)) -TimeoutMs 15000
      Emit 'faultRecovery' $recovery
      $recovered = $recovery.stdout -match 'FileTransfer finish'
    }
    Emit 'hilogHelp' (Invoke-Client -ClientArguments @('-t', $Target, 'shell', 'hilog -h') -Limit 20000)
    Emit 'hidumperHelp' (Invoke-Client -ClientArguments @('-t', $Target, 'shell', 'hidumper -h') -Limit 16000)
    $ready = $true
  } else { Emit 'processSnapshot' $probe }
  $sceneErrors = Invoke-Client -ClientArguments @('-t', $Target, 'shell',
    'hilog -x -L E,F -e "sceneboard|SceneBoard|LIFECYCLE|AppDfr"') -Limit 32000
  Emit 'sceneErrors' $sceneErrors
  foreach ($sceneId in @(Find-SceneProcessIds $probe.stdout $sceneErrors.stdout)) {
    $logs = Invoke-Client -ClientArguments @('-t', $Target, 'shell', "hilog -x -P $sceneId") -Limit 32000
    if (-not $pidLogs.ContainsKey($sceneId) -or $pidLogs[$sceneId] -cne $logs.stdout) {
      Emit 'sceneProcessLog' @{pid=$sceneId; result=$logs}
      $pidLogs[$sceneId] = $logs.stdout
    }
  }
  $listing = Invoke-Client -ClientArguments @('-t', $Target, 'shell',
    'for d in /data/log/faultlog/faultlogger /data/log/faultlog/temp /data/log/eventlog; do echo DIR:$d; ls -1 "$d"; done')
  Emit 'faultListing' $listing
  $directory = ''
  foreach ($line in ($listing.stdout -split '\r?\n')) {
    $name = $line.Trim()
    if ($name -match '^DIR:(/data/log/(faultlog/(faultlogger|temp)|eventlog))$') {
      $directory = $Matches[1]; continue
    }
    if ($directory.Length -eq 0 -or $name -notmatch '^[A-Za-z0-9._-]+$' -or
      $name -notmatch '(?i)sceneboard|freeze|cppcrash|jscrash|render|lifecycle|stack|anr') { continue }
    $key = "$directory/$name"
    $fault = Invoke-Client -ClientArguments @('-t', $Target, 'shell',
      "cat $key") -Limit 32000
    if (-not (Test-FaultCapture $fault)) {
      Emit 'faultReadError' @{name=$key; result=$fault}
      continue
    }
    if (-not $seen.ContainsKey($key) -or $seen[$key] -cne $fault.stdout) {
      Emit 'fault' @{name=$key; result=$fault}
      $seen[$key] = $fault.stdout
    }
  }
  Start-Sleep -Seconds 6
}
Emit 'monitorEnd' @{lastShellReady=$ready; faultCount=$seen.Count}
