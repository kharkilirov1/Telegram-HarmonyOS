$ErrorActionPreference = 'Stop'
$path = Join-Path $PSScriptRoot 'capture-emulator-scene-fault.ps1'
$tokens = $null; $errors = $null
$ast = [Management.Automation.Language.Parser]::ParseFile($path, [ref]$tokens, [ref]$errors)
if ($errors.Count -gt 0) { throw ($errors | Out-String) }
foreach ($name in @('Find-FreshKernelPanic', 'Test-GuestReady', 'Find-SceneProcessIds', 'Test-FaultCapture')) {
  $definition = $ast.Find({param($node) $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq $name}, $true)
  if (-not $definition) { throw "Missing actual helper: $name" }
  . ([scriptblock]::Create($definition.Extent.Text))
}
$passed = 0
function Check([bool]$Condition, [string]$Label) {
  if (-not $Condition) { throw $Label }
  $script:passed++
}
$start = [datetime]'2026-09-06T02:43:18'
$old = '2026-09-06 02:30:31.002 [333] Kernel panic - not syncing: sysrq'
$fresh = '2026-09-06 02:45:31.002 [333] Kernel panic - not syncing: sysrq'
Check (@(Find-FreshKernelPanic @($old) $start).Count -eq 0) 'Reopened log must not resurrect old panic'
Check (@(Find-FreshKernelPanic @($old, $fresh) $start).Count -eq 1) 'Fresh panic must engage'
Check (@(Find-FreshKernelPanic @('Kernel panic - not syncing: no timestamp') $start).Count -eq 0) 'Undated panic is not a current witness'
Check (Test-GuestReady @{exit=0;timeout=$false;stdout="WAVE10_READY`r`nSun Sep 6"}) 'Exact remote sentinel should pass'
Check (-not (Test-GuestReady @{exit=0;timeout=$false;stdout='[Fail] echo WAVE10_READY could not execute'})) 'Error echo is not a shell witness'
Check (-not (Test-GuestReady @{exit=1;timeout=$false;stdout='WAVE10_READY'})) 'Failed client is not ready'
Check (-not (Test-GuestReady @{exit=0;timeout=$true;stdout='WAVE10_READY'})) 'Timed-out client is not ready'
$processes = "20020011 2329 149 76 05:45:55 ? 00:00:10 com.ohos.sceneboard`n" +
  'shell 2445 1139 2 05:46:07 ? 00:00:00 sh -c ps -ef | grep -i scene'
$ids = @(Find-SceneProcessIds $processes 'key:3561_20020011_com.ohos.sceneboard key:2329_20020011_com.ohos.sceneboard')
Check ($ids.Count -eq 2 -and $ids -contains 2329 -and $ids -contains 3561) 'Actual process and timeout PID, never grep process'
Check (@(Find-SceneProcessIds '' 'key:999999999999999_1_com.ohos.sceneboard').Count -eq 0) 'Invalid PID cannot form a command'
Check (Test-FaultCapture @{exit=0;timeout=$false;stdout="Generated by HiviewDFX@OpenHarmony`r`nReason:LIFECYCLE_TIMEOUT"}) 'Actual fault header should pass'
Check (-not (Test-FaultCapture @{exit=0;timeout=$false;stdout='[Fail][E001005] Device not found or connected'})) 'HDC exit zero with failure text is not a fault'
Check (-not (Test-FaultCapture @{exit=0;timeout=$false;stdout='cat: Permission denied'})) 'Permission error is not a fault'
Check (-not (Test-FaultCapture @{exit=0;timeout=$true;stdout='Generated by HiviewDFX@OpenHarmony'})) 'Timed-out fault read is not successful'
Check (-not (Test-FaultCapture @{exit=1;timeout=$false;stdout='Generated by HiviewDFX@OpenHarmony'})) 'Failed fault read is not successful'
"Emulator capture helpers: $passed/14 PASS"
